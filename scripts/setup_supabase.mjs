/**
 * AtYourScan - Supabase Autonomous Setup Script
 * 
 * This script automates:
 * 1. Creating the 'AtYourScan' project via Supabase Management API.
 * 2. Polling until database provisioning completes.
 * 3. Executing schema.sql (tables, constraints, indexes, realtime publication).
 * 4. Fetching the API URL and anon public key.
 * 5. Writing `.env.local` and updating `supabase.js`.
 * 
 * Usage:
 *   $env:SUPABASE_ACCESS_TOKEN="sbp_your_token_here"
 *   node scripts/setup_supabase.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

const ACCESS_TOKEN = process.env.SUPABASE_ACCESS_TOKEN;
const DB_PASSWORD = process.env.SUPABASE_DB_PASSWORD || 'AyS#2026_9xPzK8lYtueWTt!Db';
const REGION = process.env.SUPABASE_REGION || 'ap-south-1'; // Default: Mumbai, India

if (!ACCESS_TOKEN) {
  console.error('\x1b[31m[ERROR] SUPABASE_ACCESS_TOKEN is required.\x1b[0m');
  console.log('\nTo generate one:');
  console.log('1. Go to https://supabase.com/dashboard/account/tokens');
  console.log('2. Click "Generate new token"');
  console.log('3. Run:\n   $env:SUPABASE_ACCESS_TOKEN="sbp_xxx"\n   node scripts/setup_supabase.mjs\n');
  process.exit(1);
}

const headers = {
  'Authorization': `Bearer ${ACCESS_TOKEN}`,
  'Content-Type': 'application/json',
};

async function api(endpoint, options = {}) {
  const url = `https://api.supabase.com/v1${endpoint}`;
  const res = await fetch(url, { ...options, headers: { ...headers, ...options.headers } });
  const data = await res.json().catch(() => null);
  if (!res.ok) {
    throw new Error(`Supabase API error (${res.status} ${res.statusText}): ${JSON.stringify(data)}`);
  }
  return data;
}

async function main() {
  console.log('\x1b[36m=== AtYourScan: Autonomous Supabase Backend Provisioning ===\x1b[0m\n');

  // Step 1: Get Organizations
  console.log('[1/5] Fetching Supabase Organizations...');
  const orgs = await api('/organizations');
  if (!orgs || orgs.length === 0) {
    throw new Error('No organizations found for this Supabase account.');
  }
  const orgId = orgs[0].id;
  console.log(`Found Organization: ${orgs[0].name} (${orgId})`);

  // Step 2: Create Project
  console.log(`\n[2/5] Creating project "AtYourScan" in region "${REGION}"...`);
  const project = await api('/projects', {
    method: 'POST',
    body: JSON.stringify({
      name: 'AtYourScan',
      organization_id: orgId,
      db_pass: DB_PASSWORD,
      region: REGION,
      plan: 'free'
    }),
  });

  const projectRef = project.id;
  console.log(`Project creation initiated! Reference ID: ${projectRef}`);

  // Step 3: Wait for Project to be ACTIVE_HEALTHY
  console.log('\n[3/5] Waiting for project provisioning to complete (this typically takes 1-2 minutes)...');
  let isReady = false;
  while (!isReady) {
    await new Promise((r) => setTimeout(r, 6000));
    const status = await api(`/projects/${projectRef}`);
    process.stdout.write(`Status: ${status.status}...\r`);
    if (status.status === 'ACTIVE_HEALTHY') {
      isReady = true;
      console.log('\nDatabase is provisioned and healthy!');
    }
  }

  // Step 4: Execute Schema SQL
  console.log('\n[4/5] Executing schema.sql (tables, indexes, realtime publication)...');
  const sqlContent = fs.readFileSync(path.join(rootDir, 'schema.sql'), 'utf-8');
  await api(`/projects/${projectRef}/database/query`, {
    method: 'POST',
    body: JSON.stringify({ query: sqlContent }),
  });
  console.log('Schema and Realtime publication applied successfully!');

  // Step 5: Extract API Keys
  console.log('\n[5/5] Extracting API credentials...');
  const apiKeys = await api(`/projects/${projectRef}/api-keys`);
  const anonKeyObj = apiKeys.find((k) => k.name === 'anon');
  const anonKey = anonKeyObj ? anonKeyObj.api_key : '';
  const projectUrl = `https://${projectRef}.supabase.co`;

  console.log('\n\x1b[32m=== Provisioning Complete! ===\x1b[0m');
  console.log(`Project URL: ${projectUrl}`);
  console.log(`Anon Public Key: ${anonKey}`);
  console.log(`DB Password: ${DB_PASSWORD}`);

  // Write .env.local
  const envContent = `# Auto-generated by AtYourScan setup script
NEXT_PUBLIC_SUPABASE_URL=${projectUrl}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
DATABASE_URL=postgresql://postgres:${encodeURIComponent(DB_PASSWORD)}@db.${projectRef}.supabase.co:5432/postgres
`;
  fs.writeFileSync(path.join(rootDir, '.env.local'), envContent);
  console.log('Saved credentials to .env.local');
}

main().catch((err) => {
  console.error('\n\x1b[31m[FAILED]\x1b[0m', err.message);
  process.exit(1);
});
